def getsub(x, y):
    return sbox[x*16+y]

def subkey(word:int):
    x = (word>>4)&0x0F
    y = word&0x0f
    return getsub(x,y)

def shiftrow(_matrix:list):
    output = _matrix.copy()
    output[1] = _matrix[5]
    output[5] = _matrix[9]
    output[9] = _matrix[13]
    output[13] = _matrix[1]
    output[2] = _matrix[10]
    output[6] = _matrix[14]
    output[10] = _matrix[2]
    output[14] = _matrix[6]
    output[3] = _matrix[15]
    output[7] = _matrix[3]
    output[11] = _matrix[7]
    output[15] = _matrix[11]
    return output

def mixcolumn(_matrix:list):
    output:list = _matrix.copy()
    def mul2mod(val:int):
        val = val << 1
        if val > 0xFF:
            val = val ^ 0b100011011
        return val
    def mul3mod(val:int):
        tmp = val
        val = val << 1
        val ^= tmp
        if val > 0xFF:
            val = val ^ 0b100011011
        return val
    arr = {0,4,8,12}
    for i in arr:
        output[i] = mul2mod(_matrix[i]) ^ mul3mod(_matrix[i+1]) ^ _matrix[i+2] ^ _matrix[i+3]
        output[i+1] = _matrix[i] ^ mul2mod(_matrix[i+1]) ^ mul3mod(_matrix[i+2]) ^ _matrix[i+3]
        output[i+2] = _matrix[i] ^ _matrix[i+1] ^ mul2mod(_matrix[i+2]) ^ mul3mod(_matrix[i+3])
        output[i+3] = mul3mod(_matrix[i]) ^ _matrix[i+1] ^ _matrix[i+2] ^ mul2mod(_matrix[i+3])
    return output


def keyschedule(key:int):
    word = [0]*44
    word[0] = (key>>96)&0xFFFFFFFF
    word[1] = (key>>64)&0xFFFFFFFF
    word[2] = (key>>32)&0xFFFFFFFF
    word[3] = key&0xFFFFFFFF

    def round(roundnum:int):
        word[roundnum*4+0] = word[(roundnum-1)*4+0]
        word[roundnum*4+1] = word[(roundnum-1)*4+1]
        word[roundnum*4+2] = word[(roundnum-1)*4+2]
        word[roundnum*4+3] = word[(roundnum-1)*4+3]
        rc = 0b00000001
        def mul2mod(val:int):
            val = val << 1
            if val > 0xFF:
                val = val ^ 0b100011011
            return val
        for i in range(roundnum-1):
            rc = mul2mod(rc)

        gword = word[roundnum*4+3]
        gword3 = subkey((gword>>24)&0xFF)
        gword0 = subkey((gword>>16)&0xFF) ^ rc
        gword1 = subkey((gword>>8)&0xFF)
        gword2 = subkey(gword&0xFF)
        gword = (gword0 << 24) | (gword1 << 16) | (gword2 << 8) | gword3
        word[roundnum*4] = int(gword) ^ word[roundnum*4]
        word[roundnum*4+1] = word[roundnum*4+1] ^ word[roundnum*4]
        word[roundnum*4+2] = word[roundnum*4+2] ^ word[roundnum*4+1]
        word[roundnum*4+3] = word[roundnum*4+3] ^ word[roundnum*4+2]
        if roundnum >= 10:
            return
        else:
            return round(roundnum+1)
    round(1)
    return word

def addroundkey(_matrix:list, round_key:list):
    output = []
    for i in range(16):
        output.append(_matrix[i] ^ round_key[i])
    return output


def perform_round(_matrix:list, key:int):
    expanded = keyschedule(key)
    initial_key = [0]*16
    round_one_key = [0]*16

    for i in range(4):
        initial_key[i*4+0] = (expanded[i]>>24)&0xFF
        initial_key[i*4+1] = (expanded[i]>>16)&0xFF
        initial_key[i*4+2] = (expanded[i]>>8)&0xFF
        initial_key[i*4+3] = expanded[i]&0xFF

        round_one_key[i*4+0] = (expanded[i+4]>>24)&0xFF
        round_one_key[i*4+1] = (expanded[i+4]>>16)&0xFF
        round_one_key[i*4+2] = (expanded[i+4]>>8)&0xFF
        round_one_key[i*4+3] = expanded[i+4]&0xFF

    state = addroundkey(_matrix, initial_key)
    for i in range(16):
        state[i] = subkey(state[i])
    state = shiftrow(state)
    state = mixcolumn(state)
    return addroundkey(state, round_one_key)
